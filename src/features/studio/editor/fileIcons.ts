/** The icon for a file, by its name. */
export function fileIcon(name: string): string {
  const lower = name.toLowerCase();
  const exact = NAMES[lower];
  if (exact) return `${BASE}${exact}.svg`;
  if (lower.startsWith(".env")) return `${BASE}tune.svg`;
  if (lower.startsWith("dockerfile")) return `${BASE}docker.svg`;
  // "a.blade.php": try "blade.php", then "php".
  const parts = lower.split(".");
  for (let i = 1; i < parts.length; i++) {
    const icon = EXTENSIONS[parts.slice(i).join(".")];
    if (icon) return `${BASE}${icon}.svg`;
  }
  return `${BASE}file.svg`;
}

/** The icon for a folder, by its name, open or closed. */
export function folderIcon(name: string, open: boolean): string {
  const base = FOLDERS[name.toLowerCase()] ?? "folder";
  return `${BASE}${base}${open ? "-open" : ""}.svg`;
}

