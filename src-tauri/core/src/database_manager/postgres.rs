//! PostgreSQL (EDB Windows binaries).
//!
//! Verified behaviour (PostgreSQL 9.2.24): `initdb -D <dir> -U postgres
//! --auth=trust` creates a data folder; `postgres -D <dir> -p <port>` runs the
//! server in the foreground; `pg_ctl stop -D <dir> -m fast` shuts it down
//! cleanly. The data folder's own postgresql.conf is used unchanged; Zenv only
//! overrides port and listen address on the command line.

use std::ffi::OsString;
use std::io::{Read, Write};
use std::net::{SocketAddr, TcpStream};
use std::path::{Path, PathBuf};
use std::time::Duration;

use super::missing_or_empty;
use crate::error::{AppError, AppResult};
use crate::runtime_catalog::ComponentId;
use crate::runtime_manager::{probe, Installation};
use crate::web_server::{
    ConnectionInfo, Control, DataDirInfo, DataDirState, LogFile, ServerContext, ServiceAdapter, SiteModel,
    ValidationReport,
};

pub struct PostgresAdapter;

/// Major version as PostgreSQL writes it to PG_VERSION: "9.2" or "17".
pub fn major(version: &str) -> String {
    let parts: Vec<&str> = version.split('.').collect();
    match parts.first().and_then(|p| p.parse::<u32>().ok()) {
        Some(m) if m >= 10 => m.to_string(),
        _ => parts.iter().take(2).copied().collect::<Vec<_>>().join("."),
    }
}

fn sibling(install: &Installation, exe: &str) -> PathBuf {
    install.executable_path.with_file_name(exe)
}

fn data_dir<'a>(ctx: &'a ServerContext) -> AppResult<&'a Path> {
    ctx.data_dir.as_deref().ok_or_else(|| AppError::Validation("this service has no data folder".into()))
}

/// `-D` and its value come from the generated launch file's first lines.
fn listen_value(ctx: &ServerContext) -> String {
    if ctx.listen_address.is_unspecified() { "*".into() } else { ctx.listen_address.to_string() }
}

impl ServiceAdapter for PostgresAdapter {
    fn component(&self) -> ComponentId {
        ComponentId::Postgresql
    }

    /// Zenv does not replace postgresql.conf; this file records the settings
    /// it passes on the command line.
    fn main_config_name(&self) -> &'static str {
        "postgres-launch.conf"
    }

    fn supports_sites(&self) -> bool {
        false
    }

    fn needs_data_dir(&self) -> bool {
        true
    }

    fn needs_initialization(&self) -> bool {
        true
    }

    fn default_port(&self) -> u16 {
        5432
    }

    fn render_main_config(&self, _install: &Installation, ctx: &ServerContext) -> AppResult<String> {
        let dir = data_dir(ctx)?;
        Ok(format!(
            "# Generated by Zenv for service \"{}\" ({}).\n\
             # PostgreSQL reads postgresql.conf from the data folder unchanged;\n\
             # Zenv passes only these settings on the command line:\n\
             data_directory = '{}'\nport = {}\nlisten_addresses = '{}'\n",
            ctx.service_name,
            ctx.service_id,
            dir.display(),
            ctx.port,
            listen_value(ctx)
        ))
    }

    fn render_site(&self, _: &Installation, _: &ServerContext, _: &SiteModel) -> AppResult<String> {
        Err(AppError::Unsupported("PostgreSQL does not serve websites".into()))
    }

    /// Parses the data folder's configuration (`postgres -C`) without starting.
    fn validate(&self, install: &Installation, config: &Path) -> AppResult<ValidationReport> {
        let text = std::fs::read_to_string(config).unwrap_or_default();
        let dir = text
            .lines()
            .find_map(|l| l.strip_prefix("data_directory = '").and_then(|r| r.strip_suffix('\'')))
            .map(PathBuf::from)
            .ok_or_else(|| AppError::Validation("launch settings have no data folder".into()))?;
        let info = self.inspect_data_dir(install, &dir);
        if info.state != DataDirState::Initialized {
            return Ok(ValidationReport { ok: false, output: info.detail, checked_file: config.to_path_buf() });
        }
        let args: Vec<OsString> = vec!["-D".into(), dir.into_os_string(), "-C".into(), "port".into()];
        let out = probe::run_capture(&install.executable_path, &args, Duration::from_secs(20))?;
        Ok(ValidationReport {
            ok: out.code == Some(0),
            output: if out.code == Some(0) { "postgresql.conf parses correctly".into() } else { out.text.trim().to_string() },
            checked_file: config.to_path_buf(),
        })
    }

    fn launch_args(&self, _install: &Installation, config: &Path) -> Vec<OsString> {
        // Rebuilt from the launch file so the arguments always match it.
        let text = std::fs::read_to_string(config).unwrap_or_default();
        let get = |key: &str| {
            text.lines()
                .find_map(|l| l.strip_prefix(&format!("{key} = ")))
                .map(|v| v.trim_matches('\'').to_string())
                .unwrap_or_default()
        };
        vec![
            "-D".into(),
            get("data_directory").into(),
            "-p".into(),
            get("port").into(),
            "-c".into(),
            format!("listen_addresses={}", get("listen_addresses")).into(),
        ]
    }

    fn request_graceful_stop(&self, ctl: &Control<'_>) -> AppResult<()> {
        let dir = data_dir(ctl.ctx)?;
        let args: Vec<OsString> = vec!["stop".into(), "-D".into(), dir.into(), "-m".into(), "fast".into(), "-W".into()];
        let out = probe::run_capture(&sibling(ctl.install, "pg_ctl.exe"), &args, Duration::from_secs(15))?;
        if out.code == Some(0) { Ok(()) } else { Err(AppError::Platform(format!("pg_ctl stop failed: {}", out.text.trim()))) }
    }

    fn graceful_timeout(&self) -> Duration {
        Duration::from_secs(30)
    }

    fn request_reload(&self, ctl: &Control<'_>) -> AppResult<()> {
        let dir = data_dir(ctl.ctx)?;
        let args: Vec<OsString> = vec!["reload".into(), "-D".into(), dir.into()];
        let out = probe::run_capture(&sibling(ctl.install, "pg_ctl.exe"), &args, Duration::from_secs(15))?;
        if out.code == Some(0) { Ok(()) } else { Err(AppError::Platform(out.text)) }
    }

    /// PostgreSQL logs to stderr, which Zenv captures as the process log.
    fn log_files(&self, _ctx: &ServerContext) -> Vec<LogFile> {
        vec![]
    }

    fn inspect_data_dir(&self, install: &Installation, dir: &Path) -> DataDirInfo {
        match missing_or_empty(dir) {
            Some(true) => DataDirInfo::new(if dir.exists() { DataDirState::Empty } else { DataDirState::Missing }, "not initialized yet"),
            None => DataDirInfo::new(DataDirState::Foreign, "cannot read the folder"),
            Some(false) => match std::fs::read_to_string(dir.join("PG_VERSION")) {
                Ok(v) => {
                    let found = v.trim().to_string();
                    let want = major(&install.version);
                    if found == want {
                        DataDirInfo::new(DataDirState::Initialized, format!("PostgreSQL {found} data folder"))
                    } else {
                        DataDirInfo::new(
                            DataDirState::Incompatible,
                            format!("this folder belongs to PostgreSQL {found}, but the installation is {want}; Zenv does not upgrade data folders"),
                        )
                    }
                }
                Err(_) => DataDirInfo::new(DataDirState::Foreign, "contains files that are not a PostgreSQL data folder"),
            },
        }
    }

    fn initialize_data_dir(&self, install: &Installation, ctx: &ServerContext) -> AppResult<String> {
        let dir = data_dir(ctx)?;
        if missing_or_empty(dir) != Some(true) {
            return Err(AppError::Conflict(format!("{} is not empty; Zenv only initializes empty folders", dir.display())));
        }
        let args: Vec<OsString> = vec![
            "-D".into(),
            dir.into(),
            "-U".into(),
            "postgres".into(),
            "-E".into(),
            "UTF8".into(),
            "--locale=C".into(),
            "--auth=trust".into(),
        ];
        let out = probe::run_capture(&sibling(install, "initdb.exe"), &args, Duration::from_secs(180))?;
        if out.code != Some(0) {
            return Err(AppError::StartFailed {
                message: "initdb could not initialize the data folder".into(),
                log_tail: out.text.lines().map(str::to_string).collect(),
            });
        }
        Ok(out.text)
    }

    fn connection_info(&self, ctx: &ServerContext) -> Option<ConnectionInfo> {
        Some(ConnectionInfo {
            host: "127.0.0.1".into(),
            port: ctx.port,
            user: Some("postgres".into()),
            password: Some(String::new()),
            database: Some("postgres".into()),
            url: format!("postgresql://postgres@127.0.0.1:{}/postgres", ctx.port),
            note: Some("A folder initialized by Zenv trusts local connections, so no password is needed.".into()),
        })
    }

    /// SSLRequest: any PostgreSQL server answers with a single 'S' or 'N'.
    fn probe(&self, addr: SocketAddr) -> Result<String, String> {
        let mut s = TcpStream::connect_timeout(&addr, Duration::from_secs(3)).map_err(|e| e.to_string())?;
        s.set_read_timeout(Some(Duration::from_secs(5))).ok();
        s.write_all(&[0, 0, 0, 8, 0x04, 0xd2, 0x16, 0x2f]).map_err(|e| e.to_string())?;
        let mut b = [0u8; 1];
        s.read_exact(&mut b).map_err(|e| format!("no answer: {e}"))?;
        match b[0] {
            b'S' | b'N' => Ok("PostgreSQL is accepting connections".into()),
            other => Err(format!("unexpected answer {other:#x}; is this PostgreSQL?")),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::web_server::tests_support::{ctx, fake_install};

    #[test]
    fn majors_follow_pg_version_files() {
        assert_eq!(major("9.2.24"), "9.2");
        assert_eq!(major("17.2"), "17");
        assert_eq!(major("16"), "16");
    }

    #[test]
    fn refuses_other_major_versions_and_foreign_folders() {
        let dir = tempfile::tempdir().unwrap();
        let install = fake_install(ComponentId::Postgresql, "9.2.24", dir.path());
        let d = dir.path().join("pg");
        std::fs::create_dir_all(&d).unwrap();
        std::fs::write(d.join("random.txt"), "").unwrap();
        assert_eq!(PostgresAdapter.inspect_data_dir(&install, &d).state, DataDirState::Foreign);
        std::fs::write(d.join("PG_VERSION"), "17\n").unwrap();
        let info = PostgresAdapter.inspect_data_dir(&install, &d);
        assert_eq!(info.state, DataDirState::Incompatible);
        assert!(info.detail.contains("17") && info.detail.contains("9.2"));
        std::fs::write(d.join("PG_VERSION"), "9.2\n").unwrap();
        assert_eq!(PostgresAdapter.inspect_data_dir(&install, &d).state, DataDirState::Initialized);
    }

    #[test]
    fn launch_args_come_from_the_launch_file() {
        let dir = tempfile::tempdir().unwrap();
        let install = fake_install(ComponentId::Postgresql, "9.2.24", dir.path());
        let c = ctx(dir.path(), Some(dir.path().join("pg")));
        let text = PostgresAdapter.render_main_config(&install, &c).unwrap();
        let file = dir.path().join("postgres-launch.conf");
        std::fs::write(&file, text).unwrap();
        let args: Vec<String> = PostgresAdapter.launch_args(&install, &file).iter().map(|a| a.to_string_lossy().into_owned()).collect();
        assert_eq!(args[0], "-D");
        assert!(args[1].ends_with("pg"));
        assert_eq!(&args[2..], ["-p", "8080", "-c", "listen_addresses=127.0.0.1"]);
    }
}
